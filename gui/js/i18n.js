window.appLanguage = window.__appLanguage || 'english';

function t(key, vars) {
  const dict = I18N[window.appLanguage] || I18N.english;
  let text = dict[key] !== undefined ? dict[key] : (I18N.english[key] !== undefined ? I18N.english[key] : key);
  if (vars) {
    Object.keys(vars).forEach((k) => {
      text = text.replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]);
    });
  }
  return text;
}

function applyI18n(lang) {
  if (lang && I18N[lang]) window.appLanguage = lang;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  // Tooltips live in data-tip; re-translate them from their i18n keys.
  document.querySelectorAll('[data-tip-i18n]').forEach((el) => {
    el.dataset.tip = t(el.dataset.tipI18n);
  });
}

document.addEventListener('DOMContentLoaded', () => applyI18n());
if (document.readyState !== 'loading') applyI18n();
